    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if(KodeAktivitas.getText().trim().equals("")){
            Valid.textKosong(BtnAktivitas,"tipe aktivitas");
        }else if(KodeKelas.getText().trim().equals("")){
            Valid.textKosong(BtnKelas,"kelompok risiko pasien");
        }else if(KodeKewaspadaan.getText().trim().equals("")){
            Valid.textKosong(BtnKewaspadaan,"kelas kewaspadaan");
        }else{
            if(Sequel.menyimpantf("pcra_icra_matriks_kelas_kewaspadaan","?,?,?","Tipe Aktivitas dan Kelompok Risiko Pasien",3,new String[]{
                    KodeAktivitas.getText(),KodeKelas.getText(),KodeKewaspadaan.getText()
                })==true){
                tabMode.addRow(new Object[]{
                    KodeAktivitas.getText(),NamaAktivitas.getText(),KodeKelas.getText(),NamaKelas.getText(),KodeKewaspadaan.getText(),NamaKewaspadaan.getText()
                });
                emptTeks();
                LCount.setText(""+tabMode.getRowCount());
            }
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

