    private void tampil() {
        Valid.tabelKosong(tabMode);
        try{
            ps=koneksi.prepareStatement(
                "select pcra_icra_matriks_kelas_kewaspadaan.kode_aktivitas,pcra_icra_jenis_aktivitas_proyek.nama_aktivitas,pcra_icra_matriks_kelas_kewaspadaan.kode_kelas,"+
                "pcra_icra_kelas_risiko_pencegahan.nama_kelas,pcra_icra_matriks_kelas_kewaspadaan.kode_kewaspadaan,pcra_icra_kelas_kewaspadaan.nama_kewaspadaan "+
                "from pcra_icra_matriks_kelas_kewaspadaan "+
                "inner join pcra_icra_jenis_aktivitas_proyek on pcra_icra_jenis_aktivitas_proyek.kode_aktivitas=pcra_icra_matriks_kelas_kewaspadaan.kode_aktivitas "+
                "inner join pcra_icra_kelas_risiko_pencegahan on pcra_icra_kelas_risiko_pencegahan.kode_kelas=pcra_icra_matriks_kelas_kewaspadaan.kode_kelas "+
                "inner join pcra_icra_kelas_kewaspadaan on pcra_icra_kelas_kewaspadaan.kode_kewaspadaan=pcra_icra_matriks_kelas_kewaspadaan.kode_kewaspadaan "+
                (TCari.getText().trim().equals("")?"":"where pcra_icra_jenis_aktivitas_proyek.nama_aktivitas like ? or pcra_icra_kelas_risiko_pencegahan.nama_kelas like ? or pcra_icra_kelas_kewaspadaan.nama_kewaspadaan like ? ")+
                "order by pcra_icra_matriks_kelas_kewaspadaan.kode_aktivitas,pcra_icra_matriks_kelas_kewaspadaan.kode_kelas"
            );
            try {
                if(!TCari.getText().trim().equals("")){
                    ps.setString(1,"%"+TCari.getText().trim()+"%");
                    ps.setString(2,"%"+TCari.getText().trim()+"%");
                    ps.setString(3,"%"+TCari.getText().trim()+"%");
                }
                rs=ps.executeQuery();
                while(rs.next()){
                    tabMode.addRow(new Object[]{
                        rs.getString(1),rs.getString(2),rs.getString(3),rs.getString(4),rs.getString(5),rs.getString(6)
                    });
                }
            } catch (Exception e) {
                System.out.println(e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            } 
        }catch(Exception e){
            System.out.println("Notifikasi : "+e);
        }
        LCount.setText(""+tabMode.getRowCount());
    }

