CREATE TABLE `penilaian_bishop_scor` (
  `no_rawat` varchar(17) NOT NULL,
  `tanggal` datetime NOT NULL,
  `pembukaan` enum('0 cm (Tertutup)','1-2 cm','3-4 cm','>= 5 cm') NOT NULL,
  `skor_pembukaan` tinyint(3) unsigned NOT NULL,
  `pendataran` enum('0-30 %','40-50 %','60-70 %','>= 80 %') NOT NULL,
  `skor_pendataran` tinyint(3) unsigned NOT NULL,
  `station` enum('-3','-2','-1 atau 0','+1 atau +2') NOT NULL,
  `skor_station` tinyint(3) unsigned NOT NULL,
  `konsistensi` enum('Keras','Sedang','Lunak') NOT NULL,
  `skor_konsistensi` tinyint(3) unsigned NOT NULL,
  `posisi` enum('Posterior','Tengah','Anterior') NOT NULL,
  `skor_posisi` tinyint(3) unsigned NOT NULL,
  `skor` tinyint(3) unsigned NOT NULL,
  `kategori` enum('Belum Matang','Menengah','Matang') NOT NULL,
  `keterangan` varchar(255) DEFAULT NULL,
  `kd_dokter` varchar(20) NOT NULL,
  PRIMARY KEY (`no_rawat`),
  KEY `kd_dokter` (`kd_dokter`),
  CONSTRAINT `penilaian_bishop_scor_ibfk_1` FOREIGN KEY (`no_rawat`) REFERENCES `reg_periksa` (`no_rawat`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `penilaian_bishop_scor_ibfk_2` FOREIGN KEY (`kd_dokter`) REFERENCES `dokter` (`kd_dokter`) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci;
